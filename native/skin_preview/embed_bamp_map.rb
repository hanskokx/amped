# Regenerates bamp_map.inc, the layer-to-bitmap map of Bamp skins
# (https://github.com/dp-mason/bamp) for the bitmaps the previews draw, from
# the amped_bamp_skin package's assets/bamp/spec.json. Run it after
# regenerating that file (its tool/bamp_spec_to_json.rb), with the path of
# the file as the argument (or in AMPED_BAMP_SPEC).
#
#   ruby embed_bamp_map.rb path/to/amped_bamp_skin/assets/bamp/spec.json
require "json"

here = File.expand_path(__dir__)
spec = JSON.parse(File.read(ARGV[0] || ENV.fetch("AMPED_BAMP_SPEC")))
files = %w[main.bmp titlebar.bmp cbuttons.bmp playpaus.bmp posbar.bmp volume.bmp
           balance.bmp monoster.bmp shufrep.bmp text.bmp eqmain.bmp pledit.bmp]

out = []
out << "// Generated by embed_bamp_map.rb from the Bamp skin specification. Do not edit."
out << "static const char* const kBampLayers[] = {"
spec["layers"].each { |l| out << %(    "#{l["file"]}",) }
out << "};"
out << "#define BAMP_LAYER_COUNT #{spec["layers"].length}"
out << ""
out << "// Resolution of each bitmap, in kFileNames order, and its height when the"
out << "// slider handle is left out (0 when it has none)."
out << "static const int kBampSizes[][3] = {"
files.each do |f|
  w = spec["classic"][f]
  out << "    {#{w["resolution"][0]}, #{w["resolution"][1]}, #{w["withoutHandle"] ? w["withoutHandle"][1] : 0}},  // #{f}"
end
out << "};"
out << ""
out << "// Layer, bitmap, region in the layer (x0 y0 x1 y1), position in the bitmap,"
out << "// flags (1: optional slider handle, 2: drawn four times too large)."
out << "typedef struct {"
out << "  short layer, file, x0, y0, x1, y1, dx, dy, flags;"
out << "} BampMap;"
out << "static const BampMap kBampMaps[] = {"
spec["layers"].each_with_index do |l, i|
  l["maps"].each do |m|
    fi = files.index(m["dest"])
    next unless fi
    d = spec["classic"][m["dest"]]["regions"][m["name"]]
    flags = (m["optionalHandle"] ? 1 : 0) | (m["name"] == "eq_viz_spectrum" ? 2 : 0)
    r = m["region"]
    out << "    {#{i}, #{fi}, #{r[0]}, #{r[1]}, #{r[2]}, #{r[3]}, #{d[0]}, #{d[1]}, #{flags}},"
  end
end
out << "};"
File.write("#{here}/bamp_map.inc", out.join("\n") + "\n")
