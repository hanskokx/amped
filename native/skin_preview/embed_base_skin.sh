#!/bin/sh
# Regenerates base_skin.inc, the base skin archive embedded as a C array,
# which the previews fall back to for the files a skin leaves out. Run it
# after changing assets/skins/base-amped.wsz (needs `sips`, `zip` and `xxd`).
#
# The native renderer reads BMP bitmaps only, so the PNG and JPEG ones of the
# base skin are converted first (their transparency is dropped, as it is for
# every classic skin).
set -e
here=$(cd "$(dirname "$0")" && pwd)
base="$here/../../assets/skins/base-amped.wsz"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
mkdir "$work/skin"
unzip -q "$base" -d "$work/skin"
find "$work/skin" -type f \( -iname '*.png' -o -iname '*.jpg' -o -iname '*.jpeg' \) |
while read -r image; do
  target="${image%.*}.bmp"
  # A BMP of the same name is already there: keep it.
  if [ ! -e "$target" ]; then
    sips -s format bmp "$image" --out "$target" >/dev/null
  fi
  rm -f "$image"
done
(cd "$work/skin" && zip -qr -X "$work/base.zip" .)
{
  echo "// Generated by embed_base_skin.sh from assets/skins/base-amped.wsz."
  echo "// Do not edit."
  (cd "$work" && xxd -i base.zip) |
    sed -e 's/^unsigned char base_zip\[\]/static const unsigned char kBaseSkin[]/' \
        -e 's/^unsigned int base_zip_len = \(.*\);/static const unsigned int kBaseSkinSize = \1;/'
} > "$here/base_skin.inc"
